import { Ionicons } from '@expo/vector-icons';
import { useState } from 'react';
import { Pressable, Share, StyleSheet, Text, View } from 'react-native';

import { shopApi } from '@/api/endpoints';
import type { GstRow } from '@/api/types';
import { GradientButton } from '@/components/Buttons';
import { GlassCard, HeroCard, SectionHeader } from '@/components/Glass';
import { Header } from '@/components/Header';
import { Screen } from '@/components/Screen';
import { addMonths, monthKey, monthLabel } from '@/lib/dates';
import { rupee } from '@/lib/money';
import { useApi } from '@/lib/useApi';
import { useTheme } from '@/theme/ThemeContext';

/** GSTR-3B style summary: output GST on sales minus input tax credit on purchases. */
export default function GstReportScreen() {
  const { theme } = useTheme();
  const [month, setMonth] = useState(monthKey(new Date()));
  const report = useApi(() => shopApi.gst(month), [month]);
  const r = report.data;
  const current = monthKey(new Date());

  const share = () => {
    if (!r) return;
    const lines = (rows: GstRow[]) => rows.map((x) => `  ${x.rate}%: taxable ${rupee(x.taxablePaise)}, GST ${rupee(x.gstPaise)}`).join('\n') || '  none';
    Share.share({
      message: `GST summary ${monthLabel(r.month)} — ${r.shopName}${r.gstin ? ` (${r.gstin})` : ''}\nSales:\n${lines(r.outward)}\nPurchases:\n${lines(r.inward)}\nOutput GST: ${rupee(r.outputTaxPaise)}\nInput tax credit: ${rupee(r.inputTaxCreditPaise)}\nNet payable: ${rupee(r.netPayablePaise)}\n(Generated by IBUVIO. Please verify with your accountant before filing.)`,
    });
  };

  return (
    <Screen refreshing={report.loading && !!r} onRefresh={report.refresh}>
      <Header title="GST Report" subtitle={r?.gstin ? `GSTIN ${r.gstin}` : 'Monthly summary for filing'} />
      <View style={styles.monthRow}>
        <Pressable onPress={() => setMonth((m) => addMonths(m, -1))} hitSlop={10} accessibilityLabel="Previous month">
          <Ionicons name="chevron-back-circle" size={36} color="#fff" />
        </Pressable>
        <Text style={styles.month}>{monthLabel(month)}</Text>
        <Pressable disabled={month >= current} onPress={() => setMonth((m) => addMonths(m, 1))} hitSlop={10} accessibilityLabel="Next month">
          <Ionicons name="chevron-forward-circle" size={36} color={month >= current ? 'rgba(255,255,255,0.4)' : '#fff'} />
        </Pressable>
      </View>
      {report.error ? <GlassCard><Text style={{ color: theme.danger }}>{report.error}</Text></GlassCard> : null}
      {r ? (
        <>
          <HeroCard>
            <Text style={{ color: '#fff' }}>Net GST payable</Text>
            <Text style={{ color: '#fff', fontSize: 38, fontWeight: '800' }}>{rupee(r.netPayablePaise, { decimals: 'always' })}</Text>
            <Text style={{ color: 'rgba(255,255,255,0.9)' }}>Output {rupee(r.outputTaxPaise)} − ITC {rupee(r.inputTaxCreditPaise)}</Text>
          </HeroCard>
          <RateTable title="Sales (outward supplies)" rows={r.outward} />
          <RateTable title="Purchases (input tax credit)" rows={r.inward} />
          <Text style={{ color: theme.textMuted, fontSize: 12, textAlign: 'center' }}>
            Amounts are treated as GST-inclusive. This summary helps with GSTR-3B; please verify with your accountant before filing.
          </Text>
          <GradientButton title="Share with accountant" icon="share-social" onPress={share} />
        </>
      ) : null}
    </Screen>
  );
}

function RateTable({ title, rows }: { title: string; rows: GstRow[] }) {
  const { theme } = useTheme();
  return (
    <GlassCard>
      <SectionHeader title={title} />
      <View style={[styles.tr, { borderBottomColor: theme.divider }]}>
        {['Rate', 'Taxable', 'CGST', 'SGST'].map((h) => <Text key={h} style={[styles.th, { color: theme.textMuted }]}>{h}</Text>)}
      </View>
      {rows.length === 0 ? <Text style={{ color: theme.textMuted, paddingVertical: 8 }}>No entries this month.</Text> : null}
      {rows.map((x) => (
        <View key={x.rate} style={[styles.tr, { borderBottomColor: theme.divider }]}>
          <Text style={[styles.td, { color: theme.text }]}>{x.rate}%</Text>
          <Text style={[styles.td, { color: theme.text }]}>{rupee(x.taxablePaise)}</Text>
          <Text style={[styles.td, { color: theme.text }]}>{rupee(x.cgstPaise)}</Text>
          <Text style={[styles.td, { color: theme.text }]}>{rupee(x.sgstPaise)}</Text>
        </View>
      ))}
    </GlassCard>
  );
}

const styles = StyleSheet.create({
  monthRow: { flexDirection: 'row', alignItems: 'center', justifyContent: 'space-between' },
  month: { color: '#fff', fontSize: 20, fontWeight: '700' },
  tr: { flexDirection: 'row', paddingVertical: 8, borderBottomWidth: 1 },
  th: { flex: 1, fontWeight: '700', fontSize: 13 },
  td: { flex: 1, fontSize: 14 },
});
